/**
 * Regenerates packages/shared/src/maps/stairData.ts from the client map builders.
 * Run: pnpm --filter @mwar/web gen:stairs   (then rebuild @mwar/shared)
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { stairToTuple } from '@mwar/shared';
import { buildMaps } from './headlessMaps';

export function renderStairData(small: readonly (readonly unknown[])[], large: readonly (readonly unknown[])[]): string {
  const rows = (list: readonly (readonly unknown[])[]) => list.map((t) => `  [${t.join(', ')}],`).join('\n');
  return `// GENERATED by apps/web/scripts/gen-stair-data.ts (pnpm --filter @mwar/web gen:stairs) - do not edit by hand.
// World-space solid staircases of each client map, used by the game server's bullet line-of-sight check.
import type { StairTuple } from './stairs';

export const SMALL_MAP_STAIRS: readonly StairTuple[] = [
${rows(small)}
];

export const LARGE_MAP_STAIRS: readonly StairTuple[] = [
${rows(large)}
];
`;
}

export async function collectStairTuples() {
  const { smallWorld, largeWorld } = await buildMaps();
  return { small: smallWorld.stairs.map(stairToTuple), large: largeWorld.stairs.map(stairToTuple) };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  collectStairTuples().then(({ small, large }) => {
    const out = new URL('../../../packages/shared/src/maps/stairData.ts', import.meta.url);
    writeFileSync(out, renderStairData(small, large));
    console.log(`stairData.ts written: small=${small.length} stairs, large=${large.length} stairs`);
  });
}
